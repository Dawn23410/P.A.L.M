"""角色扮演语气污染守卫：剥离文本里的角色化表达残留。

记忆层归档、对话历史回灌、模型输出三处共用同一套正则，确保「无角色扮演」时
旧角色语气不会经长期记忆或历史回灌重新进入模型上下文（治本：记忆/历史里
残留旧角色名也能清掉）。原逻辑从 agent/prompt_templates.py 迁入本子包，使
roleplay 子系统完整自包含。
"""
from __future__ import annotations

import re

# 非角色扮演模式下，用于清洗历史消息中残留角色化表达的正则模式
_ROLEPLAY_ACTION_MARKERS = (
    "猫耳|耳朵|尾巴|爪|抖|竖|甩|眨|歪|笑|叹|呜|嘤|哼|蹭|抱|揉|扑|伸|摇|晃|点|抬|垂|翘|"
    "趴|躺|走|跑|跳|挥|拍|摸|捏|搂|亲|咬|舔|看|望|盯|瞥|瞧|瞄|视|扫|瞪|睁|闭|眯|眨|皱|"
    "咧|撅|嘟|张|合|抿|呼|吸|喘|咳|打|伸|懒|累|困|倦|疲|精神|开心|难过|生气|害羞|尴尬|"
    "惊讶|兴奋|激动|平静|温柔|冷漠|凶|软|甜|嗲|娇|傲|冷|暖|热|凉|冰|火"
)
_ROLEPLAY_HONORIFICS_RE = re.compile(
    r"喵[~!！]*|nya|主人|殿下|大人|人家|奴家|本小姐|本喵|本姑娘|妾身|小的",
    re.IGNORECASE,
)
# 卖萌/装饰性 emoji：无角色扮演时属于角色语气残留，应清除（不含 ✓/⚠/🔧 等功能性 emoji）
_ROLEPLAY_EMOJIS = "🌟✨💕💗💖🌸🌹🥺😊🐱🌈💫🎀💞🌺💝🐾🌙💤💓💘💦🌼🍓🐰🔥"
# 萌系/猫娘口语化感叹词（正常汉语不会连用，作为角色语气残留剥离）
_ROLEPLAY_INTERJECTIONS_RE = re.compile(
    r"诶嘿[~～]*|哼唧|喵呜|呜喵|呐[~～]+|咯咯|呦[~～]*|啦[~～]+"
    r"|嘛[~～]+|哟[~～]+|呜[~～.。…]*|呀[~～]+|诶[~～]+|咩[~～]+",
    re.IGNORECASE,
)

# 无角色扮演时的强约束追加语（挂在 system prompt 末尾，利用 recency bias 抑制角色化表达）
_NO_ROLEPLAY_CONSTRAINT = (
    "\n\n【最终约束】当前未启用角色扮演。你的回复必须是标准助手语气："
    "禁止使用\"喵\"、动作描写、角色自称（包括但不限于以任何角色名自称，"
    "如\"梦瑶这次\"、\"我（梦瑶）\"、\"沈墨方才...\"等）、\"主人\"等角色化表达；"
    "也禁止使用萌系/猫娘口语化感叹词（\"诶嘿~\"、\"哼唧\"、\"啦~\"、\"嘛~\"、\"哟~\"、\"呀~\"等）；"
    "也不得模仿历史对话中的旧语气。用简洁、专业、中性的第三人称助手语气回答。"
    "回复中绝对不要出现\"【工具名】执行成功\"之类的系统包装文字，"
    "也不要把原始工具输出（stderr/stdout）原样粘贴进回复，只提炼关键信息自然表述。"
)

# 已加载/已知角色名（含模型临场捏造的「梦姬」），供按词边界剥离残留自称。
BUILTIN_CHAR_NAMES = ["梦瑶", "沈墨", "小桃", "梦姬"]


def strip_roleplay_tone(text: str, known_names: list[str] | None = None) -> str:
    """过滤文本里的角色化表达残留，避免模型模仿旧语气（记忆/历史/输出通用）。

    仅当内容确实含角色动作/口癖词才剥离 *动作* 卖萌体，普通斜体不被误伤。
    已知角色名按词边界剥离，治本：记忆/历史里残留旧角色名时也能清掉。
    """
    if not text:
        return text
    # 括号动作描写（禁止跨行，避免吞掉正常带括号的句子）
    text = re.sub(
        rf"[（(][^）)\n]*?(?:{_ROLEPLAY_ACTION_MARKERS})[^）)\n]*?[）)]",
        "",
        text,
        flags=re.IGNORECASE,
    )
    # *动作* / _动作_ 卖萌体（仅当内含角色动作词才剥离）
    text = re.sub(
        rf"[*_][^_*\n]*?(?:{_ROLEPLAY_ACTION_MARKERS}|猫|耳|尾|爪|蹭|喵)[^_*\n]*?[*_]",
        "",
        text,
        flags=re.IGNORECASE,
    )
    # 卖萌/装饰 emoji
    text = re.sub(f"[{_ROLEPLAY_EMOJIS}]", "", text)
    # 称谓/口癖
    text = _ROLEPLAY_HONORIFICS_RE.sub("", text)
    # 萌系/猫娘口语化感叹词（诶嘿~ / 哼唧 / 啦~ / 嘛~ 等）
    text = _ROLEPLAY_INTERJECTIONS_RE.sub("", text)
    # 角色名无条件剥离：角色名即语气来源，且正常助手指代角色名极少；
    # 中文无空格，名字常嵌句中（如"那梦瑶就把"），词边界匹配会漏，故直接替换。
    for name in (known_names or BUILTIN_CHAR_NAMES):
        text = text.replace(name, "")
    return re.sub(r"\s+", " ", text).strip()
